"""tools/feedback.py: an owner reply that quotes a whole agent comment is an owner comment (#3068). The footer of
the agent counts only outside the quoted lines (">")."""
import feedback

FOOTER = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"


def comment(cid, body, login=feedback.OWNER):
    return {"id": cid, "body": body, "user": {"login": login}, "created_at": "2026-10-28T12:00:00Z",
            "performed_via_github_app": None}


def test_a_reply_that_quotes_a_whole_agent_comment_is_listed():
    reply = comment(1, "> Is the new menu clear?\n>\n> ---\n> _Generated by [Claude Code](https://claude.ai/code)_\n\n"
                       "No, it is not. Please change it first.")
    assert feedback.by_owner(reply)
    assert [c["id"] for c in feedback.unanswered([reply], set())] == [1]


def test_an_agent_comment_and_a_short_quote_keep_their_result():
    assert not feedback.by_owner(comment(2, "Taken over." + FOOTER))
    assert not feedback.by_owner(comment(3, "> Do this\n\nDone." + FOOTER))          # the agent quotes the owner
    assert feedback.by_owner(comment(4, "> Is the new menu clear?\n\nYes."))
