"""The PreToolUse hook guard-body.sh blocks an MCP issue, comment or PR body that is only a file path (#4250)."""
import json
import os
import subprocess

import pytest

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HOOK = os.path.join(ROOT, ".claude", "hooks", "guard-body.sh")
FOOTER = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_\n"


def run(body):
    return subprocess.run([HOOK], input=json.dumps({"tool_input": {"body": body}}), capture_output=True,
                          text=True).returncode


@pytest.mark.parametrize("body", ["@/tmp/x/t.md", " @/tmp/x/t.md \n", "\n@/tmp/x/t.md" + FOOTER])
def test_blocks(body):
    assert run(body) == 2, body


@pytest.mark.parametrize("body", ["## Goal\nFix it." + FOOTER, "Read @/tmp/x/t.md for the log." + FOOTER, ""])
def test_allows(body):
    assert run(body) == 0, body
