"""Several GitHub logins steer the agents (decision #4229): each login of `owners` gives feedback, and Automerge holds
a PR that changes the owners until an owner approves it (#4241)."""
import base64
import json
import os
import subprocess
import sys

import pytest

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "tools"))
import agent_config  # noqa: E402
import feedback  # noqa: E402
import owner_gate  # noqa: E402
from test_automerge_failure import FAKE_GH, gate, merge_function  # noqa: E402

FOOTER = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"
CONFIG = {"owner": "anna", "owners": ["anna", "ben"]}


def comment(login, body="Do this first."):
    return {"id": 1, "user": {"login": login}, "body": body, "created_at": "2026-10-29T10:00:00Z"}


def test_the_owners_default_to_the_owner():
    assert agent_config.owners({"owner": "anna"}) == ["anna"]
    assert agent_config.owners(CONFIG) == ["anna", "ben"]


def test_each_owner_gives_feedback_and_no_other_login():
    logins = agent_config.owners(CONFIG)
    assert feedback.by_owner(comment("anna"), logins) and feedback.by_owner(comment("ben"), logins)
    assert not feedback.by_owner(comment("carl"), logins)
    assert not any(feedback.by_owner(comment(name, "Done." + FOOTER), logins) for name in logins)
    assert [c["id"] for c in feedback.unanswered([comment("ben")], set(), logins)] == [1]


def test_only_the_steering_keys_count():
    old = 'owner = "anna"\nrepo = "a/b"\n'
    assert owner_gate.steering(old) == owner_gate.steering(old.replace("a/b", "a/c"))
    assert owner_gate.steering(old) != owner_gate.steering(old + 'owners = ["anna", "carl"]\n')
    assert owner_gate.steering(old) != owner_gate.steering(old + '[accounts.x]\nruns = 1\n')


def test_the_last_review_of_an_owner_decides():
    ok, no = {"state": "APPROVED", "user": {"login": "ben"}}, {"state": "CHANGES_REQUESTED", "user": {"login": "ben"}}
    assert owner_gate.approved([no, ok], ["anna", "ben"])
    assert not owner_gate.approved([ok, no], ["anna", "ben"])
    assert not owner_gate.approved([{"state": "APPROVED", "user": {"login": "carl"}}], ["anna", "ben"])


def merge_calls(tmp_path, head_toml, reviews):
    """Run merge() of automerge.yml for a green PR whose head has `head_toml`. Gives the merge calls."""
    (tmp_path / "bin").mkdir()
    gh = tmp_path / "bin" / "gh"
    gh.write_text(FAKE_GH.format(python=sys.executable))
    gh.chmod(0o755)
    main = 'owner = "anna"\nowners = ["anna", "ben"]\n'
    enc = lambda t: {"content": base64.b64encode(t.encode()).decode()}  # noqa: E731
    (tmp_path / "table.json").write_text(json.dumps({
        "GET repos/o/r/contents/agent.toml?ref=abc": [enc(head_toml), 0],
        "GET repos/o/r/contents/agent.toml?ref=main": [enc(main), 0],
        "GET repos/o/r/pulls/7/reviews": [reviews, 0],
        "GET repos/o/r/pulls/7": [{"merged": True, "head": {"sha": "abc"}}, 0]}))
    gate(tmp_path, main)
    pr = json.dumps({"number": 7, "head": {"ref": "agent/7-x", "sha": "abc"}, "labels": [], "body": "A change."})
    script = "\n".join(["R=o/r merged=0 conflict=0 AGENT=true", merge_function(), f"merge '{pr}' abc"])
    env = dict(os.environ, PATH=f"{tmp_path / 'bin'}:{os.environ['PATH']}", GH_LOG=str(tmp_path / "log"),
               GH_TABLE=str(tmp_path / "table.json"), RUNNER_TEMP=str(tmp_path))
    p = subprocess.run(["bash", "-c", script], cwd=tmp_path, env=env, capture_output=True, text=True)
    assert p.returncode == 0, p.stderr
    calls = [json.loads(line) for line in (tmp_path / "log").read_text().splitlines()]
    return [c for c in calls if c[1] == "repos/o/r/pulls/7/merge"]


pytestmark = pytest.mark.skipif(subprocess.run(["which", "jq"], capture_output=True).returncode != 0,
                                reason="the fake gh needs jq")
ADD = 'owner = "anna"\nowners = ["anna", "ben", "carl"]\n'


def test_automerge_holds_a_change_of_the_owners(tmp_path):
    assert merge_calls(tmp_path, ADD, []) == []


def test_automerge_merges_a_change_of_the_owners_after_an_owner_approval(tmp_path):
    assert merge_calls(tmp_path, ADD, [{"state": "APPROVED", "user": {"login": "ben"}}])


def test_automerge_merges_a_pr_that_keeps_the_owners(tmp_path):
    assert merge_calls(tmp_path, 'owner = "anna"\nowners = ["anna", "ben"]\nrepo = "x/y"\n', [])
