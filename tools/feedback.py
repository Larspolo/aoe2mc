"""Owner comments without an answer (#971): the comments of the owner in the last hours with no comment lock.

A run locks an owner comment before it answers it (`tools/claim.py ID --comment` pushes `claim/comment-ID`), so the
lock ref is the memory of "handled". Autopilot step 3 read only the comments after `last_run`, and each run moves
`last_run`: a comment between the start of one run and the report of another was never read (#820). So step 3 reads
a window of hours and takes the comments without a lock. The window starts 6 hours before the earlier of now and
`last_run` (the state comment of the status issue): after a stop of the runs (the label `paused`, a used-up quota) the
first run still lists the comments of the stop (#3060).

    python3 tools/feedback.py              # the owner comments of the window without a lock ref
    python3 tools/feedback.py --hours 12
    python3 tools/feedback.py --count      # only the number (dashboard, `tools/health.py`)

The agent comments with the login of the owner too: a comment with the Claude Code footer or through the GitHub App
is from the agent. An agent comment with neither shows here: lock it (`--comment`) when it needs no answer.
The comment locks live one day (`claims.yml`), so keep the window below 24 hours (MAX_HOURS).
"""
import argparse
import datetime
import json
import math
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from agent_config import CONFIG  # noqa: E402
from dashboard import api, pages  # noqa: E402

OWNER = CONFIG["owner"]
AGENT = "Generated by [Claude Code]"      # the footer of each agent comment (same login as the owner)
HOURS = 6                                 # a time, not merged PRs: each owner comment gets an answer in time (#2039)
MAX_HOURS = 23                            # below the one day of the comment locks: a longer window lists handled ones


def by_owner(comment, owner=OWNER):
    """A comment of the owner: the owner's login, no footer and no app (`gh api` of a cloud run posts as the app
    "claude")."""
    return ((comment.get("user") or {}).get("login") == owner and AGENT not in (comment.get("body") or "")
            and not comment.get("performed_via_github_app"))


def locks(refs):
    """The comment IDs of the lock refs `refs/heads/claim/comment-ID`."""
    out = set()
    for r in refs:
        tail = r["ref"].rsplit("/claim/comment-", 1)
        if len(tail) == 2 and tail[1].isdigit():
            out.add(int(tail[1]))
    return out


def unanswered(comments, locked, owner=OWNER):
    """The owner comments whose ID has no lock, oldest first."""
    return sorted((c for c in comments if by_owner(c, owner) and c["id"] not in locked), key=lambda c: c["created_at"])


def issue_number(comment):
    """The issue or PR number of an issue comment (issue_url) or a PR review comment (pull_request_url)."""
    url = comment.get("issue_url") or comment.get("pull_request_url") or ""
    return int(url.rsplit("/", 1)[1]) if url.rsplit("/", 1)[-1].isdigit() else None


def last_run():
    """The time `last_run` of the state comment of the status issue (each run report sets it), or None."""
    try:
        m = re.search(r"<!-- agent-state: (\{.*?\}) -->", api(f"issues/{CONFIG['status']['issue']}").get("body") or "")
        return datetime.datetime.fromisoformat(json.loads(m[1])["last_run"].replace("Z", "+00:00"))
    except Exception:                       # no access, no state comment, no time: the window of HOURS
        return None


def window(now, last):
    """The hours of the window: HOURS before the earlier of now and `last` (the last run report), at most MAX_HOURS.
    Normally `last` is a few minutes old and the window stays about HOURS; after a long stop it reaches back to it."""
    gap = (now - last).total_seconds() / 3600 if last else 0
    return min(HOURS + max(gap, 0), MAX_HOURS)


def fetch(hours=None, now=None):
    """The owner comments without a lock in the last `hours` (None: window())."""
    now = now or datetime.datetime.now(datetime.timezone.utc)
    hours = window(now, last_run()) if hours is None else hours
    iso = f"{now - datetime.timedelta(hours=hours):%Y-%m-%dT%H:%M:%SZ}"
    limit = max(10, 2 * math.ceil(hours))   # pages of 100: about 1500 comments a day, so 200 an hour leaves room
    # since= filters by updated_at: keep only the comments made in the window
    comments = []
    for path in (f"issues/comments?since={iso}", f"pulls/comments?since={iso}"):
        found = pages(path, limit)
        if len(found) >= limit * 100:       # pages() reads oldest first: the newest comments are cut
            print(f"feedback: {path} has more than {limit * 100} comments, the newest are cut", file=sys.stderr)
        comments += [c for c in found if c["created_at"] >= iso]
    try:
        refs = api("git/matching-refs/heads/claim/comment-")
    except Exception:                       # no lock ref at all, or no access: count all
        refs = []
    return unanswered(comments, locks(refs))


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--hours", type=float, help=f"the window (default: {HOURS} before the last run report, at most "
                    f"{MAX_HOURS})")
    ap.add_argument("--count", action="store_true", help="print only the number")
    a = ap.parse_args(argv)
    found = fetch(a.hours)
    if a.count:
        print(len(found))
        return 0
    for c in found:
        line = (c.get("body") or "").strip().splitlines()[0][:100] if (c.get("body") or "").strip() else ""
        print(f"{c['id']} #{issue_number(c)} {c['created_at']} {line}")
    window = "the window" if a.hours is None else f"the last {a.hours:g} hours"
    print(f"{len(found)} owner comments without a lock in {window}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
