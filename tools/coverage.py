#!/usr/bin/env python3
"""
Coverage report of the AoE2 object types: which types get their own design or mapping, and which use a fallback.

Usage:
    python3 tools/coverage.py [OUT.md]        # default: docs/coverage.md

Fallbacks: buildings that use the `generic` design, other objects that `place_objects` skips, and units that
`units.classify()` skips. The default foot soldier (`units.infantry`) is correct for many infantry units, so the
report shows it as "default infantry", not as a fallback.
"""
import contextlib
import io
import os
import sys
from collections import Counter

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

import aoe2mc  # noqa: E402
import buildings  # noqa: E402
import units  # noqa: E402


def building_rows():
    from AoE2ScenarioParser.datasets.buildings import BuildingInfo
    rows = []
    for e in BuildingInfo:
        if e.name == "RUINS":
            rows.append((e.name, "ruins (in place_objects)", False))
            continue
        fn, kw = buildings.select(e.name)
        rows.append((e.name, fn.__name__ + "".join(f" {k}={v}" for k, v in kw.items()), fn is buildings.generic))
    return rows


def other_rows():
    """Place each object alone on a small flat map and read the counters of place_objects."""
    from AoE2ScenarioParser.datasets.other import OtherInfo
    size = 12
    rows = []
    for e in OtherInfo:
        cols = aoe2mc.Columns(size, np.zeros((size, size), np.int16), np.zeros((size, size), np.float32),
                              {0: "GRASS_1"}, 4, 3, np.random.default_rng(1))
        o = dict(kind="O", name=e.name, player=0, x=size / 2, y=size / 2, rotation=0.0, hero=False, garrisoned=False)
        with contextlib.redirect_stdout(io.StringIO()):
            _, stats = aoe2mc.place_objects([o], {}, cols, np.random.default_rng(1))
        skipped = stats["skipped (other objects)"] > 0
        if "FISH" in e.name:
            result = "fish (entity)"
        else:
            result = ", ".join(sorted(k for k, v in stats.items() if v)) or "nothing (on purpose)"
        rows.append((e.name, result, skipped))
    return rows


def summary(desc):
    """Entity description -> 'horse (zombie)'."""
    out = str(desc["id"]).replace("minecraft:", "")
    riders = [summary(p) for p in desc.get("Passengers", [])]
    return out + (f" ({', '.join(riders)})" if riders else "")


def unit_rows(enum, hero):
    rows, default = [], []
    original = units.infantry

    def record(n, t):
        default.append(n)
        return original(n, t)
    units.infantry = record
    try:
        for e in enum:
            desc = units.classify(e.name, hero)
            if desc is None:
                rows.append((e.name, "skipped", True))
            else:
                rows.append((e.name, summary(desc) + (" – default infantry" if e.name in default else ""), False))
    finally:
        units.infantry = original
    return rows


def groups():
    """[(title, rows)] with rows = [(name, result, fallback)]."""
    from AoE2ScenarioParser.datasets.heroes import HeroInfo
    from AoE2ScenarioParser.datasets.units import UnitInfo
    return [("Buildings", building_rows()), ("Other objects", other_rows()),
            ("Units", unit_rows(UnitInfo, False)), ("Heroes", unit_rows(HeroInfo, True))]


def counts(groups):
    """{title: {"types", "own", "default", "fallback"}}: the numbers of the summary table."""
    out = {}
    for title, rows in groups:
        default = sum("default infantry" in r for _, r, _ in rows)
        fallback = sum(f for _, _, f in rows)
        out[title] = {"types": len(rows), "own": len(rows) - default - fallback, "default": default, "fallback": fallback}
    return out


def report(groups):
    lines = ["# Coverage of the AoE2 object types", "",
             "Generated by `python3 tools/coverage.py`. Do not edit by hand.", "",
             "| Group | Types | Own design or mapping | Default infantry | Fallback |", "|---|---|---|---|---|"]
    for title, c in counts(groups).items():
        lines.append(f"| {title} | {c['types']} | {c['own']} | {c['default']} | {c['fallback']} |")
    for title, rows in groups:
        lines += ["", f"## {title}", "", "| Name | Result | Fallback |", "|---|---|---|"]
        lines += [f"| {n} | {r} | {'yes' if f else 'no'} |" for n, r, f in rows]
        top = Counter(r for _, r, f in rows if not f).most_common(3)
        lines += ["", "Most common results: " + ", ".join(f"{r} ({k})" for r, k in top) + "."]
    return "\n".join(lines) + "\n"


def main(argv):
    out = argv[1] if len(argv) > 1 else os.path.join(ROOT, "docs", "coverage.md")
    text = report(groups())
    with open(out, "w") as f:
        f.write(text)
    print(f"wrote {out}")


if __name__ == "__main__":
    main(sys.argv)
