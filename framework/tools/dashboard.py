"""Build the dashboard in the body of the status issue (#1) from GitHub.

Many runs work in parallel, so no run writes the dashboard from its own view. This script reads the labels,
comments and PRs and writes the sections "Waiting for you", "Working on", "Next up" and "Recently done".
It keeps the agent-state comment and the "Process changes" section of the current body.

    python3 framework/tools/dashboard.py            # update the body of the status issue
    python3 framework/tools/dashboard.py --dry-run  # print the body
    python3 framework/tools/dashboard.py --next     # print the ticket candidates in pick order (autopilot step 5), with
                                          # the files and functions that they share with the work in progress

Token: GITHUB_TOKEN. Without it the script uses `gh api` (cloud sessions). Python standard library only.
"""
