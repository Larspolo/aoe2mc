#!/usr/bin/env python3
"""Close an epic by itself when the ticket of its last criterion merges (#835).

The epic check (`queue.md`, "Epics and refill") ends its comment with the line `Close this epic when #N merges.` when
all other criteria are met. When #N then closes as completed by a merged PR (or by the label `close`, #6065), and the
epic has no other open sub-issue and no open "Part of #E" ticket, `close.yml` runs this tool: an evidence comment and the label `close`. Before this, the
pacer started one more deep run only to read the criteria again (7 % of the list price of 100 PRs, 2026-11-03).

    python3 framework/tools/epic_autoclose.py            # print the epics that close, change nothing
    python3 framework/tools/epic_autoclose.py --apply    # comment, add the label `close`; stdout: the epic numbers

The selection functions take plain JSON and functions for the reads, so the tests need no network.
"""
import argparse
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

LINE = re.compile(r"(?:^|\s)Close this epic (?:when|after) #(\d+) merges\.$")   # "after": the form of #813
AGENT = "Generated by [Claude Code]"      # the footer of each agent comment (`feedback.AGENT`)


def own_text(comment):
    """The body with no quoted lines (">"): a quote reply copies the footer of an agent comment (#3068)."""
    return "\n".join(line for line in (comment.get("body") or "").splitlines() if not line.lstrip().startswith(">"))


def by_agent(comment):
    """A comment of a run: a login of `owners` (the runs post as the owner) with the footer, or the app "claude" (`gh api`
    of a cloud run, `feedback.by_owner`). Any user can write the footer: the login keeps a stranger from closing an epic."""
    from agent_config import owners
    return (comment.get("user") or {}).get("login") in owners() and \
        (AGENT in own_text(comment) or bool(comment.get("performed_via_github_app")))


def by_bot(comment):
    """A comment of a workflow (github-actions[bot]): no run and no owner wrote it."""
    return (comment.get("user") or {}).get("type") == "Bot" and not comment.get("performed_via_github_app")


def close_line(comments):
    """N of `Close this epic when #N merges.` at the end of the last comment of a run or a person, else None.
    A later comment of a person (an owner question) needs a run: then None. The footer does not count."""
    last = next((c for c in reversed(comments) if not by_bot(c)), None)
    if not last or not by_agent(last):
        return None
    text = own_text(last).split("\n---\n_Generated by")[0]
    lines = [line.strip() for line in text.splitlines() if line.strip()]
    m = LINE.search(lines[-1]) if lines else None
    return int(m[1]) if m else None


def checks(issues, now=None):
    """The open epics that wait for an epic check (`usage.refill_need`): no open sub-issue, no open "Part of #E"
    ticket, no hold."""
    import usage
    return usage.epic_checks(issues, now)


def select(issues, comments_of, merged_pr, now=None):
    """[(E, N, PR, comment)]: each epic of `checks` whose last comment ends with the close line and whose #N merged.
    comments_of(E): the comments of E; merged_pr(N): the merged PR that closed #N as completed, else None."""
    out = []
    for e in checks(issues, now):
        comments = comments_of(e)
        n = close_line(comments)
        if n is None:
            continue
        pr = merged_pr(n)
        if pr:
            out.append((e, n, pr, next(c for c in reversed(comments) if not by_bot(c))))
    return out


# ---- GitHub REST ----------------------------------------------------------------------------
def comments_of(number):
    import dashboard
    return dashboard.pages(f"issues/{number}/comments")


def merged_pr(number):
    """The number of the merged PR that closed #number as completed, `LABEL` when it closed as completed after the label
    `close` of an owner login (a check ticket with no PR, #6065), else None (closed as not planned, by hand, open)."""
    import dashboard
    issue = dashboard.api(f"issues/{number}")
    if issue.get("state") != "closed" or issue.get("state_reason") != "completed":
        return None
    events = dashboard.pages(f"issues/{number}/events")
    closed = [e for e in events if e.get("event") == "closed"]
    if not closed:
        return None
    if sha := closed[-1].get("commit_id"):
        prs = [p for p in dashboard.api(f"commits/{sha}/pulls") if p.get("merged_at")]
        return prs[0]["number"] if prs else None
    # automerge.yml closes the ticket by the API before the closing word does (#4847): that event has no commit
    # (#6061). Then take the merge commit of a "referenced" event whose PR merged at most API_CLOSE before the close.
    at = stamp(closed[-1].get("created_at"))
    for e in reversed(events):
        if e.get("event") != "referenced" or not e.get("commit_id"):
            continue
        for p in dashboard.api(f"commits/{e['commit_id']}/pulls"):
            if p.get("merged_at") and 0 <= at - stamp(p["merged_at"]) <= API_CLOSE:
                return p["number"]
    return LABEL if by_label(events, at) else None


def by_label(events, at):
    """True when an owner login (the runs post as the owner) added the label `close` before the close at `at`: close.yml
    then closed the ticket after the evidence comment of the run (`owner.md`, "Close an issue")."""
    from agent_config import owners
    return any(e.get("event") == "labeled" and (e.get("label") or {}).get("name") == LABEL
               and (e.get("actor") or {}).get("login") in owners() and stamp(e.get("created_at")) <= at for e in events)


LABEL = "close"           # merged_pr: the ticket closed by the label `close` (dashboard.CLOSE), not by a PR
API_CLOSE = 15 * 60       # seconds from the merge of a PR to the close of its ticket by automerge.yml


def stamp(text):
    """Unix seconds of a GitHub time ("2026-11-07T14:51:46Z"); no time: 0."""
    import datetime
    return datetime.datetime.fromisoformat(text.replace("Z", "+00:00")).timestamp() if text else 0


def ready(epic):
    """(N, PR) when the open epic closes by itself (the pacer skips its epic check), else None. An error: None."""
    try:
        n = close_line(comments_of(epic))
        pr = merged_pr(n) if n is not None else None
        return (n, pr) if pr else None
    except Exception as e:                                  # a GitHub error: the epic check runs as before
        print(f"epic autoclose #{epic}: {e}", file=sys.stderr)
        return None


def evidence(n, pr, comment):
    how = "it closed with the label `close`" if pr == LABEL else f"PR #{pr} merged it"
    return (f"All criteria are met: the epic check ({comment.get('html_url', 'the last agent comment')}) left only #{n}, "
            f"and {how}. Closed by `close.yml` (`framework/tools/epic_autoclose.py`, #835). The roadmap "
            "line of this epic gets `[x]` in the next roadmap review.")


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--apply", action="store_true", help="comment and add the label close")
    args = ap.parse_args(argv)
    import dashboard
    for e, n, pr, comment in select(dashboard.pages("issues?state=open"), comments_of, merged_pr):
        print(f"#{e}: #{n} " + ("closed by the label close" if pr == LABEL else f"merged by PR #{pr}"), file=sys.stderr)
        if args.apply:
            dashboard.api(f"issues/{e}/comments", "POST", {"body": evidence(n, pr, comment)})
            dashboard.api(f"issues/{e}/labels", "POST", {"labels": [dashboard.CLOSE]})
            print(e)
    return 0


if __name__ == "__main__":
    sys.exit(main())
