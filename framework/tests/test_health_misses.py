"""framework/tools/health.py: the owner tickets for the system (misses), the domain data in the code and windows of merged
PRs (#1909)."""
import datetime

import health

SINCE = datetime.datetime(2026, 10, 27, 12, 0, tzinfo=datetime.timezone.utc)
FOOTER = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"


def issue(n, body, labels=("cleanup",), app=None, created="2026-10-27T18:59:53Z", login=health.OWNER):
    return {"number": n, "body": body, "labels": [{"name": x} for x in labels], "created_at": created,
            "user": {"login": login}, "performed_via_github_app": app, "title": "T"}


def test_an_owner_ticket_for_the_system_is_a_miss():
    issues = [issue(1909, "Currently the code contains long lists."),                    # owner, free text
              issue(1864, "### Goal\n\nhttps://github.com/Larspolo/aoe2mc/pull/1845", ("tooling",)),  # owner form
              issue(1702, "## Goal\nParallel tickets ..." + FOOTER, ("process",)),         # agent, footer
              issue(1897, "## Goal\nAfter bootstrap ...", ("process",), app={"slug": "claude"}),
              issue(1806, "## Goal\nEach ticket number ...", ("tooling",)),               # agent, local session
              issue(1950, "Add a cheat code", ("feature",)),                                 # owner, not the system
              issue(1600, "Old", created="2026-10-26T10:00:00Z"),                          # before the period
              issue(1951, "A comment", login=health.OWNER + "-other")]
    assert health.misses(issues, SINCE) == [1864, 1909]
    text = health.report(SINCE, [], [], [], [], [], [], issues=issues)
    assert "Misses (owner tickets for the system, improve step 0): 2 (#1864, #1909)" in text
    assert "Misses (owner tickets for the system, improve step 0): 0" in health.report(SINCE, [], [], [], [], [], [])


def test_the_report_counts_the_data_in_the_code(tmp_path):
    (tmp_path / "list.txt").write_text("# a comment\na.py:X 2\nb.py:Y 1\n")
    rows = health.data_rows(str(tmp_path / "list.txt"))
    assert rows == [("a.py:X", 2), ("b.py:Y", 1)]
    text = health.report(SINCE, [], [], [], [], [], [], data_rows=rows)
    assert "Data in the code ([lint] data of agent.toml): 3 literals in 2 places" in text
    assert "Data in the code" not in health.report(SINCE, [], [], [], [], [], [])
    assert health.data_rows(str(tmp_path / "none.txt")) is None


def test_a_window_of_merged_prs():
    until = SINCE + datetime.timedelta(hours=1)
    times = [until - datetime.timedelta(minutes=m) for m in (5, 30, 60, 90, 150)]     # newest first
    assert health.pr_hours(times, until, 2) == (1.0, 1.5)       # the PRs at 5 and 30 min, then at 60 and 90 min
    assert health.pr_hours(times[:2], until, 2) == (0.5, 0.0)   # a young repository: the oldest merge ends it
