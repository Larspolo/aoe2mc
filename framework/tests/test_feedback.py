"""framework/tools/feedback.py lists the owner comments without a comment lock ref (#971)."""
import feedback

FOOTER = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"


def comment(cid, body, login="Larspolo", when="2026-10-26T14:00:00Z", app=None, issue=820):
    return {"id": cid, "body": body, "user": {"login": login}, "created_at": when, "performed_via_github_app": app,
            "issue_url": f"https://api.github.com/repos/Larspolo/aoe2mc/issues/{issue}"}


def test_only_owner_comments_without_a_lock_ref():
    comments = [comment(1, "Are all cheats implemented?", when="2026-10-26T14:09:00Z"),
                comment(2, "Taken over." + FOOTER),                         # agent: footer
                comment(3, "Started by `x`.", app={"slug": "claude"}),      # agent: through the GitHub App
                comment(4, "Looks good", login="someone"),                  # another user: data only
                comment(5, "A", when="2026-10-26T11:00:00Z"),
                comment(6, "Do this first")]                                # locked: another run handles it
    refs = [{"ref": "refs/heads/claim/comment-6"}, {"ref": "refs/heads/claim/938-2"},
            {"ref": "refs/heads/claim/refill-0-14"}]
    assert feedback.locks(refs) == {6}
    assert [c["id"] for c in feedback.unanswered(comments, feedback.locks(refs))] == [5, 1]


def test_issue_number_of_issue_and_review_comments():
    assert feedback.issue_number(comment(1, "x", issue=971)) == 971
    assert feedback.issue_number({"pull_request_url": "https://api.github.com/repos/o/r/pulls/951"}) == 951


def test_fetch_reads_issue_and_review_comments_of_the_window(monkeypatch):
    import datetime
    now = datetime.datetime(2026, 10, 26, 15, 0, tzinfo=datetime.timezone.utc)
    old = comment(7, "old, edited later", when="2026-10-26T08:00:00Z")      # since= filters by updated_at
    seen = []

    def pages(path, limit=10):
        seen.append(path)
        return [comment(8, "new")] if path.startswith("issues/") else [old]

    monkeypatch.setattr(feedback, "pages", pages)
    monkeypatch.setattr(feedback, "api", lambda path: [{"ref": "refs/heads/claim/comment-9"}])
    assert [c["id"] for c in feedback.fetch(6, now)] == [8]
    assert seen == ["issues/comments?since=2026-10-26T09:00:00Z", "pulls/comments?since=2026-10-26T09:00:00Z"]


def test_dashboard_and_health_show_the_count():
    import datetime

    import dashboard
    import health
    now = datetime.datetime(2026, 10, 26, 15, 0, tzinfo=datetime.timezone.utc)
    found = [comment(1, "Are all cheats implemented?"), comment(2, "And this?"), comment(3, "A", issue=797)]
    body = dashboard.render("", [], {}, [], [], [], now, found)
    assert "Owner comments without an answer (6 h): 3 #820 #797 (`framework/tools/feedback.py`" in body
    assert "Owner comments without an answer (6 h): 0\n" in dashboard.render(body, [], {}, [], [], [], now, [])
    assert "Owner comments without an answer" not in dashboard.render("", [], {}, [], [], [], now)
    text = health.report(now - datetime.timedelta(hours=24), [], [], [], [], [], [], unanswered=found)
    assert "Owner comments without an answer (framework/tools/feedback.py): 3" in text
