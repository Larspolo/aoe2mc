"""Only a comment of an owner login (the agent posts as the owner) gives the close line of `epic_autoclose` (#835).
Any GitHub user can write the footer of an agent comment: with the footer alone, a stranger could close an epic, and
the close of the release epic makes the release (`feedback.by_owner` checks the login the same way, #4229)."""
import agent_config
import epic_autoclose

LINE = "Close this epic when #805 merges.\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"


def comment(login, app=None):
    return {"body": LINE, "user": {"login": login, "type": "User"}, "performed_via_github_app": app}


def test_a_stranger_with_the_footer_gives_no_close_line():
    assert epic_autoclose.close_line([comment("a-stranger")]) is None
    assert epic_autoclose.close_line([comment("a-stranger", app={"slug": "claude"})]) is None


def test_an_owner_login_with_the_footer_gives_the_close_line():
    assert epic_autoclose.close_line([comment(agent_config.owners()[0])]) == 805
