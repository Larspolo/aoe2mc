"""framework/tools/owner_tasks.py lists the tickets that wait for the owner, with kind and question (#983)."""
import owner_tasks

FOOTER = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"


def issue(n, title, labels=("needs-human",), body="", pr=False):
    i = {"number": n, "title": title, "labels": [{"name": x} for x in labels], "body": body, "state": "open"}
    return {**i, "pull_request": {}} if pr else i


def test_lists_needs_human_without_muted_decisions_first():
    issues = [issue(10, "Check the bot of player 2 in the game"),
              issue(11, "Decide: the order of the cheats", ("needs-human", "feature")),
              issue(12, "Muted thing", ("needs-human", "muted")),
              issue(13, "Not waiting", ("P2",)),
              issue(14, "A PR", pr=True),
              issue(5, "Show a score panel", ("needs-human", "epic"))]
    comments = {5: [{"body": "@Larspolo All criteria of this epic are met. Please close it." + FOOTER}],
                10: [{"body": "Agent check done.\n\nDoes the bot feel fast enough?" + FOOTER}]}
    found = owner_tasks.tasks(issues, comments)
    assert [t["number"] for t in found] == [11, 5, 10]
    assert [t["kind"] for t in found] == ["decision", "close", "play"]
    assert found[1]["epic"] and found[1]["question"] == "All criteria of this epic are met. Please close it."
    assert found[2]["question"] == "Does the bot feel fast enough?"


def test_kind_from_the_section_for_the_owner_wins():
    body = "## Goal\nX\n\n## For the owner\nKind: setting\n1. Open the environment.\n2. Reply \"done\".\n\n## Verify\nY"
    i = issue(7, "Check something", body=body)
    assert owner_tasks.for_owner(body) == "Kind: setting\n1. Open the environment.\n2. Reply \"done\"."
    assert owner_tasks.kind(i) == "setting"
    assert owner_tasks.show(i, [{"body": "Please close it."}]).startswith("Kind: setting")


def test_kind_from_the_title():
    assert owner_tasks.kind(issue(1, "Ask the owner to set the interaction limit again")) == "setting"
    assert owner_tasks.kind(issue(2, "Try the bootstrap on a small second repository")) == "outside"
    assert owner_tasks.kind(issue(3, "Answer each owner comment")) == "question"
