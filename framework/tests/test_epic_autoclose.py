"""An epic closes by itself when the ticket of its last criterion merges (#835): `epic_autoclose` and the skip of the
epic check in `usage.refill_need`."""
import epic_autoclose
import usage

NOW = 1_800_000_000
FOOTER = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"
CHECK = "Epic check: criteria 1 and 2 are met (#801, #802). Criterion 3 waits for #805.\n\nClose this epic when #805 merges."


def epic(number=9):
    return {"number": number, "labels": [{"name": "epic"}], "sub_issues_summary": {"total": 3, "completed": 3},
            "created_at": "2020-01-01T00:00:00Z", "body": ""}


def agent(body):
    return {"body": body + FOOTER, "user": {"login": "Larspolo", "type": "User"}, "html_url": "https://x/c/1"}


def owner(body):
    return {"body": body, "user": {"login": "Larspolo", "type": "User"}}


def bot(body):
    return {"body": body, "user": {"login": "github-actions[bot]", "type": "Bot"}}


def select(comments, closed):
    """closed: {N: PR} of the tickets that merged as completed (not planned or open: missing)."""
    return epic_autoclose.select([epic()], lambda e: comments, closed.get, now=NOW)


def test_the_line_and_a_merged_ticket_close_the_epic():
    out = select([agent(CHECK)], {805: 830})
    assert [(e, n, pr) for e, n, pr, _ in out] == [(9, 805, 830)]
    assert "#805" in epic_autoclose.evidence(805, 830, out[0][3]) and "https://x/c/1" in epic_autoclose.evidence(805, 830, out[0][3])


def test_a_ticket_closed_as_not_planned_keeps_the_epic_check():
    assert select([agent(CHECK)], {}) == []        # merged_pr gives None: not completed, or no merged PR


def test_no_line_keeps_the_epic_check():
    assert select([agent("Epic check: criterion 3 waits for #805.")], {805: 830}) == []


def test_the_line_must_end_the_comment():
    assert select([agent(CHECK + "\n\nOne more note.")], {805: 830}) == []


def test_the_form_of_813_at_the_end_of_a_line():
    assert epic_autoclose.close_line([agent("- Roadmap line: in the PR of #834. Close this epic after #834 merges.")]) == 834


def test_a_later_owner_comment_keeps_the_epic_check():
    assert select([agent(CHECK), owner("Wait, also check the photos.")], {805: 830}) == []


def test_a_later_workflow_comment_does_not_count():
    assert [e for e, *_ in select([agent(CHECK), bot("Closed by the Close workflow.")], {805: 830})] == [9]


def test_a_quoted_line_is_not_the_line():
    assert epic_autoclose.close_line([owner("> Close this epic when #805 merges.\n\nNo, not yet.")]) is None


def test_an_epic_with_an_open_sub_issue_is_no_candidate():
    e = epic() | {"sub_issues_summary": {"total": 3, "completed": 2}}
    assert epic_autoclose.select([e], lambda n: [agent(CHECK)], {805: 830}.get, now=NOW) == []


def test_refill_need_skips_the_epic_that_closes_by_itself():
    assert usage.refill_need(0, 16, [epic()], now=NOW, closing=lambda e: e == 9) == ""
    assert usage.refill_need(0, 16, [epic(), epic(10)], now=NOW, closing=lambda e: e == 9) == "epic check #10"
    assert usage.refill_need(0, 16, [epic()], now=NOW) == "epic check #9"
